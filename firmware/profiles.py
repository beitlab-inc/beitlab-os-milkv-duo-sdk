"""Resolve hardware profiles and generate the C runtime's policy tables."""

import argparse
import json
from pathlib import Path
import re

PROFILE_DIR = Path(__file__).resolve().parents[1] / "profiles"
DEFAULT_PROFILE = "beitlab_robotics_rev011"


class ProfileError(ValueError):
    pass


def _unique_keys(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ProfileError("duplicate manifest key: %s" % key)
        result[key] = value
    return result


def load_profile(name=DEFAULT_PROFILE, directory=PROFILE_DIR, _parents=()):
    if not isinstance(name, str) or not re.fullmatch(r"[a-z][a-z0-9_]*", name):
        raise ProfileError("invalid hardware profile name: %r" % name)
    if name in _parents:
        raise ProfileError("profile inheritance cycle: %s" % name)
    try:
        data = json.loads((Path(directory) / (name + ".json")).read_text(),
                          object_pairs_hook=_unique_keys)
    except (OSError, json.JSONDecodeError) as exc:
        raise ProfileError("cannot load hardware profile %r: %s" % (name, exc)) from exc
    if not isinstance(data, dict) or data.get("id") != name:
        raise ProfileError("profile id must match filename: %s" % name)
    if not isinstance(data.get("description"), str) or not data["description"]:
        raise ProfileError("profile needs a description: %s" % name)
    sources = data.get("sources")
    if not isinstance(sources, list) or not sources or any(
            not isinstance(s, str) or not s for s in sources):
        raise ProfileError("profile needs source references: %s" % name)
    parent = load_profile(data["extends"], directory, _parents + (name,)) \
        if "extends" in data else {"pins": {}, "reserved_resources": {}, "sources": [], "i2c_devices": {}}
    pins = dict(parent["pins"])
    entries = data.get("pins", {})
    if not isinstance(entries, dict):
        raise ProfileError("pins must be an object: %s" % name)
    for pad, entry in entries.items():
        if not re.fullmatch(r"[A-E](?:[0-9]|[12][0-9]|3[01])", pad):
            raise ProfileError("noncanonical pin in manifest: %s" % pad)
        if not isinstance(entry, dict) or entry.get("owner") not in (
                "application", "linux", "robot"):
            raise ProfileError("invalid pin owner: %s" % pad)
        if not isinstance(entry.get("purpose"), str) or not entry["purpose"]:
            raise ProfileError("pin needs a purpose: %s" % pad)
        if pins.get(pad, {}).get("owner") == "linux" and entry["owner"] != "linux":
            raise ProfileError("cannot release Linux pin: %s" % pad)
        if entry["owner"] == "application" and (
                pad[0] == "E" or entry.get("function") != "gpio_output" or
                entry.get("voltage") not in ("1.8", "3.3") or
                not isinstance(entry.get("connector"), str) or not entry["connector"]):
            raise ProfileError("application pin needs supported function, voltage and connector: %s" % pad)
        # Replace the whole entry: a reserved child pin must lose inherited permissions.
        pins[pad] = entry
    reserved = dict(parent["reserved_resources"])
    resources = data.get("reserved_resources", {})
    if not isinstance(resources, dict) or any(
            not re.fullmatch(r"[a-z][a-z0-9_]*", k) or not isinstance(v, str) or not v
            for k, v in resources.items()):
        raise ProfileError("invalid reserved_resources: %s" % name)
    reserved.update(resources)
    i2c = dict(parent["i2c_devices"])
    devices = data.get("i2c_devices", {})
    if not isinstance(devices, dict):
        raise ProfileError("i2c_devices must be an object: %s" % name)
    i2c.update(devices)
    for bus, addresses in i2c.items():
        # Only this carrier route has SDK mux and electrical evidence so far.
        if bus != "i2c4" or not isinstance(addresses, list) or not addresses or any(
                type(address) is not int or not 0x08 <= address <= 0x77 for address in addresses):
            raise ProfileError("invalid or unverified I2C grant: %s" % bus)
        if len(set(addresses)) != len(addresses):
            raise ProfileError("duplicate I2C address: %s" % bus)
        if any(pins.get(pad, {}).get("owner") != "robot" for pad in ("B1", "B2", "B20", "B21")):
            raise ProfileError("I2C4 grant requires the carrier's reserved B1/B2 route and B20/B21 boot-route isolation")
    return {"id": name, "description": data["description"],
            "sources": parent["sources"] + sources,
            "pins": pins, "reserved_resources": reserved, "i2c_devices": i2c}


def generate_header(profile, destination):
    quote = json.dumps  # JSON ASCII string literals are also C string literals.
    lines = ["/* Generated by firmware/profiles.py; edit the profiles/ JSON manifests. */",
             "static const char profile_name[] = %s;" % quote(profile["id"]),
             "static const struct profile_pin profile_pins[] = {"]
    for pad, entry in sorted(profile["pins"].items()):
        allowed = entry["owner"] == "application"
        reason = "" if allowed else "%s; reserved for %s" % (
            entry["purpose"], "robot firmware" if entry["owner"] == "robot" else "Linux")
        lines.append("    {%d, %d, %d, %s}," % (
            ord(pad[0]) - ord("A"), int(pad[1:]), allowed, quote(reason)))
    # Sentinel also permits a manifest with no pins/resources, without zero-length arrays.
    lines += ["    {255, 0, 0, 0}", "};",
              "static const struct profile_resource profile_resources[] = {"]
    for resource, reason in sorted(profile["reserved_resources"].items()):
        lines.append("    {%s, %s}," % (quote(resource), quote(reason)))
    lines += ["    {0, 0}", "};",
              "static const struct profile_i2c_device profile_i2c_devices[] = {"]
    for bus, addresses in sorted(profile["i2c_devices"].items()):
        for address in sorted(addresses):
            lines.append("    {%d, %d}," % (int(bus[3:]), address))
    lines += ["    {255, 0}", "};", ""]
    Path(destination).write_text("\n".join(lines))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("profile", nargs="?", default=DEFAULT_PROFILE)
    args = parser.parse_args()
    try:
        print(json.dumps(load_profile(args.profile), indent=2))
    except ProfileError as exc:
        parser.exit(2, "%s\n" % exc)
